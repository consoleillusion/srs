/**
 * Generate TypeScript types for every exposed resource, from the same registry
 * the API serves (design book, Schema). the `init` command writes them to
 * `.srs/types.ts` so a client can type its requests.
 *
 * @module
 */
import type { JSONSchemaProperty, BuiltSchema } from './schema-types.ts'
import { buildRegistry } from '../server/registry.ts'

/** PascalCase for a snake_case resource type. */
const pascal =
  (value: string) => value.split(/[_\s-]+/).map(x => x.charAt(0).toUpperCase() + x.slice(1)).join('')

/** A property name, quoted when it is not a plain identifier. */
const key = (name: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)

/** The TypeScript type of one JSON Schema property. */
const typeOf =
  (schema: JSONSchemaProperty | undefined, depth = 0): string => {
    if (!schema || depth > 8) return 'unknown'
    if (schema.enum) return schema.enum.map(x => JSON.stringify(x)).join(' | ')
    const types = [schema.type].flat().filter((x): x is string => typeof x === 'string' && x !== 'null')
    const one = (type: string): string => {
      switch (type) {
        case 'string': return 'string'
        case 'integer':
        case 'number': return 'number'
        case 'boolean': return 'boolean'
        case 'array': return `${wrap(typeOf(schema.items, depth + 1))}[]`
        case 'object':
          if (!schema.properties) return 'Record<string, unknown>'
          return `{ ${Object.entries(schema.properties).map(([name, value]) =>
            `${key(name)}${schema.required?.includes(name) ? '' : '?'}: ${typeOf(value, depth + 1)}`).join('; ')} }`
        default: return 'unknown'
      }
    }
    return types.length === 0 ? 'unknown' : types.map(one).join(' | ')
  }

const wrap = (type: string) => /[|&]/.test(type) ? `(${type})` : type

/**
 * Write the type declarations for a built schema.
 *
 * @param built - The built schema.
 * @returns The contents of `types.ts`.
 */
export const generateTypes =
  (built: BuiltSchema): string => {
    const registry = buildRegistry(built)
    const resources = [...registry.resources.values()].sort((a, b) => a.type.localeCompare(b.type))
    const lines: string[] =
      [ '// Generated by the init command from the schema files. Do not edit; run init again.'
      , ''
      , '/** A to-one relationship value. */'
      , 'export type ToOne<T extends string> = { data: { type: T, id: string } | null }'
      , '/** A to-many relationship value. */'
      , 'export type ToMany<T extends string> = { data: { type: T, id: string }[] }'
      , ''
      ]

    for (const resource of resources) {
      const name = pascal(resource.type)
      const columns = new Map(resource.definition.columns.map(x => [x.columnName, x]))
      const required = new Set(resource.definition.schema.required ?? [])
      const summary = resource.definition.schema.description
      lines.push(`/** Attributes of \`${resource.type}\`${summary ? `: ${summary}` : ''}. */`)
      lines.push(`export type ${name}Attributes = {`)
      for (const attribute of resource.attributes) {
        const column = columns.get(attribute)
        const schema = column?.schema
        const readOnly = schema?.readOnly === true || (column?.injected === true && attribute !== 'visibility')
        const nullable = !required.has(attribute)
        if (schema?.description) lines.push(`  /** ${schema.description.replaceAll('*/', '* /')} */`)
        lines.push(
          `  ${readOnly ? 'readonly ' : ''}${key(attribute)}${nullable ? '?' : ''}: `
          + `${typeOf(schema)}${nullable ? ' | null' : ''}`)
      }
      lines.push('}')
      const relationships = Object.values(resource.relationships)
      lines.push(`/** Relationships of \`${resource.type}\`. */`)
      lines.push(
        relationships.length === 0
          ? `export type ${name}Relationships = Record<string, never>`
          : `export type ${name}Relationships = {\n${relationships.map(x =>
              `  ${key(x.label)}?: ${x.cardinality === 'one' ? 'ToOne' : 'ToMany'}<${JSON.stringify(x.type)}>`).join('\n')}\n}`)
      lines.push(`/** A \`${resource.type}\` resource object. */`)
      lines.push(
        `export type ${name}Resource = { type: ${JSON.stringify(resource.type)}, id: string`
        + `, attributes: ${name}Attributes, relationships?: ${name}Relationships }`)
      lines.push('')
    }

    lines.push('/** Every resource object, by type. */')
    lines.push('export type Resources = {')
    for (const resource of resources) lines.push(`  ${key(resource.type)}: ${pascal(resource.type)}Resource`)
    lines.push('}')
    lines.push('/** A resource type name. */')
    lines.push('export type ResourceType = keyof Resources')
    lines.push('/** A JSON:API collection document of one resource type. */')
    lines.push('export type Collection<T extends ResourceType> = { data: Resources[T][] }')
    lines.push('/** A JSON:API single-resource document of one resource type. */')
    lines.push('export type Single<T extends ResourceType> = { data: Resources[T] }')
    return lines.join('\n') + '\n'
  }
